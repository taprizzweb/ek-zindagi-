/** Rewrites src/components/certificate/certificate-frame.ts from assets/certificate/frame.png. Run: npx tsx scripts/gen-frame-ts.ts */
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const bytes = readFileSync('assets/certificate/frame.png');
const { width, height } = PNG.sync.read(bytes);
writeFileSync(
  'src/components/certificate/certificate-frame.ts',
  `/* Generated by scripts/gen-frame-ts.ts from assets/certificate/frame.png. Do not edit. */
/** Photo frame with marigold garland and incense; the window is transparent so the photo shows through. */
export const FRAME_WIDTH = ${width};
export const FRAME_HEIGHT = ${height};
export const FRAME_SRC = 'data:image/png;base64,${bytes.toString('base64')}';
`,
);
console.log('certificate-frame.ts written', width, height);
